"""Global accounting checks (fail closed, exit 1 on any violation) that are not per-log replays.  All comparisons are exact
(rational arithmetic on the REPRESENTED closed boxes: a manifest cell (p0, r) represents [p0 - r, p0 + r] in exact reals; a
processed root represents its dyadic snapping cover2.dyadic_root, which is the box its leaves tile).

 1. KF runs (certs2/kf_*): the manifest's C-cells (roots) and 'outside' cells tile the rectangle [-2,2] x [-2,0] exactly; every
    outside cell lies outside the closed KF sector [38, 100] deg x [0.5, 1.8] (exact decimals; rigorous predicate); the COLLAR
    roots are the cells at t = float(0.02) = fam5.KF_COL_T_HI; the SPIKE roots are the products of the cells with the t-slabs of
    the manifest, and for every cell the snapped t-intervals are contiguous and cover fam5.KF_SPK_T exactly (the t-range that
    the SP predicate 'C inside the KF sector' relies on).
 2. Legacy runs (certs/): the manifests are exactly the root lists generated by manifests_legacy.py.
 3. cover5 families: every manifest cell is a grid cell of run_fam.GRIDS with p0 AND r equal to the exact grid encoding
    (exact float ends); per axis the represented cell intervals are contiguous (each meets the next) and cover the parameter
    range of README section 2 (exact rational bounds; pi enclosed by 3.1415926 < pi < 3.1415927); the spike t-axis is checked
    for the col and spk families together (t in [0, 3/10]); every processed root's snapped box contains its cell.
    Hence the union of the represented boxes of each family (pair) contains the product of its parameter ranges.
 4. The far threshold RF used by the far families is <= e^3, the largest radius of the polar grids (rigorous)."""
import sys, os, json, math
from fractions import Fraction as Fr
sys.path.insert(0, os.path.dirname(os.path.realpath(__file__)))
from flint import arb
from nanguard import exact_box, InexactBox, dec
from grid import dyadic_root
D = os.path.dirname(os.path.realpath(__file__)) + '/'
bad = []
def fail(m): bad.append(m); print('FAIL:', m)
def ends(c, h): return Fr(c) - Fr(h), Fr(c) + Fr(h)
PI_LO, PI_HI = Fr('3.1415926'), Fr('3.1415927')
assert arb(PI_LO.numerator)/PI_LO.denominator < arb.pi() < arb(PI_HI.numerator)/PI_HI.denominator

# ------------------------------------------------------------------------------------------------ 1. KF runs
import fam5
from regions import sector_discard
for mode in ('COLLAR', 'SPIKE'):
    m = json.load(open(D + f'manifests/kf_{mode.lower()}.json'))
    if m.get('mode') != mode or m.get('region') != 'KF' or m.get('family') != 'KF_' + mode: fail(f'kf_{mode.lower()}: family/mode/region')
    if set(m) != {'family', 'mode', 'region', 't_slabs', 'cells', 'outside', 'roots'}: fail(f'kf_{mode.lower()}: manifest keys')
    cells = [tuple(c) for c in m['cells']]; outside = [tuple(c) for c in m['outside']]
    x0, x1, y0, y1 = Fr(-2), Fr(2), Fr(-2), Fr(0)
    area = Fr(0); boxes = []
    for (cx, cy, hx, hy) in cells + outside:
        try: exact_box([cx, cy], [hx, hy])
        except InexactBox as e: fail(f'KF cell {e}')
        bx = (Fr(cx) - Fr(hx), Fr(cx) + Fr(hx), Fr(cy) - Fr(hy), Fr(cy) + Fr(hy))
        if not (Fr(hx) > 0 and Fr(hy) > 0): fail('KF cell with zero width')
        boxes.append(bx); area += 4*Fr(hx)*Fr(hy)
        if bx[0] < x0 or bx[1] > x1 or bx[2] < y0 or bx[3] > y1: fail('KF cell outside the rectangle')
    if area != (x1 - x0)*(y1 - y0): fail(f'KF cells: area {float(area)} != rectangle')   # RIGOR: info: message
    boxes.sort()
    for i in range(len(boxes)):
        for j in range(i + 1, len(boxes)):
            if boxes[j][0] >= boxes[i][1]: break
            if boxes[i][2] < boxes[j][3] and boxes[j][2] < boxes[i][3]: fail('KF cells overlap')
    disc = sector_discard('38', '100', '0.5', '1.8')
    for (cx, cy, hx, hy) in outside:
        if not disc([0.0, 0.0, cx, cy], [0.0, 0.0, hx, hy]): fail(f'KF outside cell not outside the sector: {(cx, cy, hx, hy)}')
    roots = m['roots']
    if mode == 'COLLAR':
        exp = [[f'FCOL_{j}', [fam5.KF_COL_T_HI, 0.0, cx, cy], [0.0, 0.0, hx, hy]] for j, (cx, cy, hx, hy) in enumerate(cells)]
        if roots != exp: fail('kf_collar: roots are not the cells at t = KF_COL_T_HI')
    else:
        ts = [tuple(t) for t in m['t_slabs']]
        exp = [[f'FSPK_{a}_{j}', [(t0 + t1)/2, 0.0, cx, cy], [(t1 - t0)/2, 0.0, hx, hy]]
               for a, (t0, t1) in enumerate(ts) for j, (cx, cy, hx, hy) in enumerate(cells)]
        if roots != exp: fail('kf_spike: roots are not cells x t-slabs')
        lo_req, hi_req = Fr(fam5.KF_SPK_T[0]), Fr(fam5.KF_SPK_T[1])
        for j in range(len(cells)):
            iv = sorted(ends(*[dyadic_root(r[1], r[2])[k][0] for k in (0, 1)]) for r in roots if r[0].endswith(f'_{j}') and r[0].split('_')[2] == str(j))
            if not iv or iv[0][0] > lo_req or max(b for a, b in iv) < hi_req: fail(f'kf_spike cell {j}: t-range not covered')   # RIGOR: exact: max of Fractions
            reach = iv[0][1]
            for a, b in iv[1:]:
                if a > reach: fail(f'kf_spike cell {j}: t-gap at {float(reach)}')   # RIGOR: info: message
                reach = max(reach, b)   # RIGOR: exact: max of Fractions
    print(f'KF {mode}: {len(cells)} cells, {len(outside)} outside, {len(roots)} roots checked')

# ------------------------------------------------------------------------------------------------ 2. legacy manifests
import manifests_legacy as ml
for name, famname, gen in (('crit_collar', 'COLLAR', ml.collar()), ('crit_spike_X1', 'SPIKE_X1', ml.spike()),
                           ('main_cbox', 'MAIN_CBOX', ml.main_cbox()), ('shallow_crit', 'BOX', ml.shallow())):
    m = json.load(open(D + f'manifests/{name}.json'))
    exp = [[a, [float(x) for x in b], [float(x) for x in c]] for a, b, c in gen]   # RIGOR: exact: float() of the generator's floats (the generator writes these values)
    if set(m) != {'family', 'roots'} or m['family'] != famname or m['roots'] != exp: fail(f'{name}: manifest differs from manifests_legacy.py (family {famname})')
# every processed legacy root is represented by its snapped box (the box its leaves tile): it must contain its nominal cell
def snapped_contains(roots, cells, label):
    nom = {rid: (lo, hi) for rid, lo, hi in cells}
    if set(nom) != {c[0] for c in roots}: fail(f'{label}: nominal cells and roots differ'); return
    for rid, p0, r in roots:
        sp, sr = dyadic_root(p0, r); lo, hi = nom[rid]
        for i in range(4):
            if not (Fr(sp[i]) - Fr(sr[i]) <= Fr(lo[i]) and Fr(sp[i]) + Fr(sr[i]) >= Fr(hi[i])): fail(f'{label}: root {rid} snapped box misses its nominal cell (axis {i})')
def contiguous(vals, label):
    """vals: list of (lo, hi) Fractions of consecutive cells along one axis: each starts where (or before) the previous one ends"""
    for (a0, b0), (a1, b1) in zip(vals, vals[1:]):
        if a1 > b0: fail(f'{label}: gap between {float(b0)} and {float(a1)}')   # RIGOR: info: message
for name, cells in (('crit_collar', ml.collar_cells()), ('crit_spike_X1', ml.spike_cells()), ('main_cbox', ml.main_cbox_cells()),
                    ('shallow_crit', ml.shallow_cells())):
    snapped_contains(json.load(open(D + f'manifests/{name}.json'))['roots'], cells, name)
# nominal regions: the crit runs cover t in [T1, 3/10] x CBOX (check_cbox_cover.py checks the snapped boxes against
# cbox_snapped() exactly); Theorem M: rows a_y in [0.25, 1.5479] contiguous, each row a_x in [1, x_last] with x_last >= a_y/0.3 at
# the row's top (every dart with C in CBOX (c_x < 1) has a_x > 1, and tan b_A >= 0.3 gives a_x <= a_y/0.3);
# Theorem H: the shallow cells tile the box SHALLOW_BOX exactly (shared linspace edges, end edges equal to the box).
rows = {}
for rid, lo, hi in ml.main_cbox_cells():
    a = int(rid.split('_')[1]); rows.setdefault(a, []).append((Fr(lo[0]), Fr(hi[0]), Fr(lo[1]), Fr(hi[1])))
ylist = [(v[0][2], v[0][3]) for a, v in sorted(rows.items())]
contiguous(ylist, 'main_cbox a_y rows')
if not (ylist[0][0] <= Fr('0.25') and ylist[-1][1] >= Fr(1.5479)): fail('main_cbox: a_y range')
for a, v in rows.items():
    xs = sorted((x0, x1) for x0, x1, y0, y1 in v)
    contiguous(xs, f'main_cbox row {a}')
    if not (xs[0][0] <= 1 and xs[-1][1] >= v[0][3]*Fr(10, 3)): fail(f'main_cbox row {a}: a_x range')
SB = fam5.SHALLOW_BOX
cells = ml.shallow_cells()
for i in range(4):
    edges = sorted({(Fr(lo[i]), Fr(hi[i])) for rid, lo, hi in cells})
    contiguous(edges, f'shallow axis {i}')
    if not (edges[0][0] == Fr(SB[i][0]) and edges[-1][1] == Fr(SB[i][1])): fail(f'shallow axis {i}: ends differ from SHALLOW_BOX')
print('legacy manifests, snapped boxes and nominal regions checked')

# ------------------------------------------------------------------------------------------------ 3. cover5 families
import run_fam
NEED = {'PP': [(0, '1/2pi'), (Fr('-2.5'), Fr(3)), (0, 'pi'), (Fr(-4), Fr(3))],
        'PF': [(0, '1/2pi'), (Fr('-2.5'), Fr(3)), (0, 'pi'), None],
        'FP': [(0, '1/2pi'), None, (0, 'pi'), (Fr(-4), Fr(3))],
        'FF': [(0, '1/2pi'), None, (0, 'pi'), None],
        'SP': [(0, Fr(3, 10)), None, (0, 'pi'), (Fr(-4), Fr(3))],
        'SF': [(0, Fr(3, 10)), None, (0, 'pi'), None]}
def need_hi(v): return {'1/2pi': PI_HI/2, 'pi': PI_HI}.get(v, v) if isinstance(v, str) else Fr(v)
def axis_intervals(name):
    return [[ends(c, h) for c, h in run_fam.axis_cells(*g)] for g in run_fam.GRIDS[name]]
def check_family_cells(name):
    """manifest cells = exact grid encodings; roots' snapped boxes contain their cells"""
    import itertools
    man = json.load(open(D + f'manifests/{name.lower()}.json'))
    axes = [run_fam.axis_cells(*g) for g in run_fam.GRIDS[name]]
    cells = {}
    for idx in itertools.product(*[range(len(x)) for x in axes]):
        cells[name + '_' + '_'.join(map(str, idx))] = ([axes[i][idx[i]][0] for i in range(4)], [axes[i][idx[i]][1] for i in range(4)])
    if set(man) != {'family', 'grid', 'roots', 'skipped'} or man['family'] != name: fail(f'{name}: manifest keys / family')
    seen = set()
    for c in man['roots'] + man['skipped']:
        rid, p0, r = c[0], c[1], c[2]
        if rid in seen or rid not in cells: fail(f'{name}: duplicate or unknown cell {rid}'); continue
        seen.add(rid)
        if [float(x) for x in p0] != cells[rid][0] or [float(x) for x in r] != cells[rid][1]: fail(f'{name}: cell {rid} is not the exact grid encoding')   # RIGOR: exact: float() of floats; exact equality
        try: exact_box(p0, r)
        except InexactBox as e: fail(f'{name}: cell {rid}: {e}')
    if seen != set(cells): fail(f'{name}: manifest cells != grid cells')
    for rid, p0, r in man['roots']:
        sp0, sr = dyadic_root(p0, r)
        for i in range(4):
            a, b = ends(p0[i], r[i]); sa, sb = ends(sp0[i], sr[i])
            if not (sa <= a and sb >= b): fail(f'{name}: root {rid}: snapped box does not contain the cell')
def check_axis(label, iv, req):
    lo, hi = Fr(req[0]), need_hi(req[1])
    if not iv: fail(f'{label}: no cells'); return
    if iv[0][0] > lo: fail(f'{label}: first cell starts at {float(iv[0][0])} > {float(lo)}')   # RIGOR: info: message
    reach = iv[0][1]
    for a, b in iv[1:]:
        if a > reach: fail(f'{label}: gap between {float(reach)} and {float(a)}')   # RIGOR: info: message
        reach = max(reach, b)   # RIGOR: exact: max of Fractions
    if reach < hi: fail(f'{label}: cells end at {float(reach)} < {float(hi)}')   # RIGOR: info: message
for name in ('PP', 'PF', 'FP', 'FF', 'SP_col', 'SP_spk', 'SF_col', 'SF_spk'):
    check_family_cells(name)
for name in ('PP', 'PF', 'FP', 'FF'):
    ivs = axis_intervals(name)
    for i, req in enumerate(NEED[name]):
        if req is None:
            if run_fam.GRIDS[name][i][2] is not None: fail(f'{name}: coordinate {i} should be inactive')
            continue
        check_axis(f'{name} axis {i}', ivs[i], req)
for pair, key in ((('SP_col', 'SP_spk'), 'SP'), (('SF_col', 'SF_spk'), 'SF')):
    a, b = (axis_intervals(n) for n in pair)
    for i in (1, 2, 3):
        if run_fam.GRIDS[pair[0]][i] != run_fam.GRIDS[pair[1]][i]: fail(f'{key}: col and spk grids differ on axis {i}')
    for i, req in enumerate(NEED[key]):
        if req is None:
            if run_fam.GRIDS[pair[0]][i][2] is not None: fail(f'{key}: coordinate {i} should be inactive')
            continue
        iv = sorted(a[0] + b[0]) if i == 0 else a[i]
        check_axis(f'{key} axis {i}', iv, req)
print('cover5 manifests and represented-box coverage checked')

# ------------------------------------------------------------------------------------------------ 4. far threshold
if not (arb(fam5.RF) <= arb(3).exp().lower()): fail('far threshold RF exceeds the polar grid radius e^3')
print('RF =', fam5.RF, '<= e^3 (rigorous)')
print(json.dumps(dict(accounting='ok' if not bad else 'FAILED', failures=len(bad))))
sys.exit(0 if not bad else 1)
