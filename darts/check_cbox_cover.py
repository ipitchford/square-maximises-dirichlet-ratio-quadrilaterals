"""Exact check (rational arithmetic) that the roots of the COLLAR and SPIKE runs cover the region that the MAIN-CBOX discards
'tan b_A <= 0.3 (COLLAR/SPIKE certificates, C in CBOX)' rely on:
  collar roots (t = float(0.02); Lemma 9.2 extends to all t <= float(0.02)) cover C in cbox_snapped();
  spike roots cover t in [float(0.02), 3/10] x cbox_snapped() (the discard threshold 0.3 is the exact decimal 3/10).
Boxes are the recorded (snapped) root boxes, compared in exact rational arithmetic.
Method: the grid generated by all root edges inside the target box; every grid cell centre must lie in some root."""
import json, itertools
from fractions import Fraction as Fr
from regions import cbox_snapped
def roots(path):
    return [json.loads(l)['box'] for l in open(path) if '"root_done"' in l]
def uncovered(boxes, dims, target):
    edges = []
    for j, d in enumerate(dims):
        e = {Fr(target[j][0]), Fr(target[j][1])}
        for b in boxes:
            for v in (Fr(b['p0'][d]) - Fr(b['r'][d]), Fr(b['p0'][d]) + Fr(b['r'][d])):
                if Fr(target[j][0]) < v < Fr(target[j][1]): e.add(v)
        edges.append(sorted(e))
    bad = 0
    for cell in itertools.product(*[range(len(e) - 1) for e in edges]):
        c = [(edges[j][cell[j]] + edges[j][cell[j] + 1])/2 for j in range(len(dims))]
        if not any(all(abs(c[j] - Fr(b['p0'][d])) <= Fr(b['r'][d]) for j, d in enumerate(dims)) for b in boxes): bad += 1
    return bad
(x0, x1), (y0, y1) = cbox_snapped()
col = roots('certs/crit_collar.jsonl'); spk = roots('certs/crit_spike_X1.jsonl')
ok_t = all(b['p0'][0] == 0.02 and b['r'][0] == 0 for b in col)
u1 = uncovered(col, [2, 3], [(x0, x1), (y0, y1)]); u2 = uncovered(spk, [0, 2, 3], [(Fr(0.02), Fr(3, 10)), (x0, x1), (y0, y1)])
print(json.dumps(dict(cbox_snapped=[[x0, x1], [y0, y1]], collar_at_t=0.02 if ok_t else 'WRONG', collar_uncovered_cells=u1,
                      spike_uncovered_cells=u2, ok=bool(ok_t and u1 == 0 and u2 == 0))))
import sys; sys.exit(0 if (ok_t and u1 == 0 and u2 == 0) else 1)
