include("../geom.jl"); include("../rules.jl"); include("../fsolve.jl"); include("../tm.jl"); include("../assemble.jl"); include("../criterion.jl")
using Printf
using LinearAlgebra; BLAS.set_num_threads(1)
set_order!(3)
for (p0, n) in (([0.3,0.3,0.3,0.1], 8), ([0.3,0.3,0.3,0.1], 10), ([0.3,0.3,0.3,0.1], 12))
    sol = fsolve_d(p0, n); t = @elapsed sol = fsolve_d(p0, n)
    awA = newasm(Arb); awF = newasm(Float64)
    rad = fill(0.01, 4)
    assemble_box!(awA, p0, rad, sol); assemble_box!(awF, p0, rad, sol)
    tA = @elapsed bA = assemble_box!(awA, p0, rad, sol)
    tF = @elapsed bF = assemble_box!(awF, p0, rad, sol)
    cpA = critpool(Arb); wsA = newwork(Arb)
    sbb = scalar_bounds(p0, rad); L0b = max(sbb.L_rect, sbb.L_hersch); betab = max(sbb.beta_rect_ks, L0b + sbb.gapAC)
    crit_eval!(cpA, bA.M, bA.K, bA.A2, wsA; mode = :LG, beta = betab, L0 = L0b)
    tC = @elapsed rC = crit_eval!(cpA, bA.M, bA.K, bA.A2, wsA; mode = :LG, beta = betab, L0 = L0b)
    tS = @elapsed scalar_bounds(p0, rad)
    @printf("n=%d: fsolve_d %.3fs | Float64 asm %.4fs | Arb asm %.3fs | Arb crit %.4fs | scalar bounds %.4fs | ok=%s which=%s\n", n, t, tF, tA, tC, tS, rC.ok, rC.which)
    # enclosure check: Float64 coefficients within Arb balls (approx)
    worst = maximum(abs(Float64(Arblib.midref(bA.K[4].c[k])) - bF.K[4].c[k]) / max(1e-300, Float64(Arblib.radref(bA.K[4].c[k])) + 1e-12*abs(bF.K[4].c[k])) for k in 1:TAB[].nc)
    println("   K22 coefficient agreement (|mid-F64|/(rad+1e-12|F64|)) max = ", worst, "  Arb rem=", remval(bA.K[4]), " F64 rem=", remval(bF.K[4]))
end
